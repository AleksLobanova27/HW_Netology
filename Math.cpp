#include <iostream>
#include <cmath>
#include "Math.h"

double MFunction::sum(double a, double b) { return a + b; }
double MFunction::dif(double a, double b) { return a - b; }
double MFunction::mul(double a, double b) { return a * b; }
double MFunction::div(double a, double b) { return a / b; }
double MFunction::deg(double a, double b) { return pow(a, b); }